import { githubRequest } from './github-request.js';

/**
 * Creates a draft pull request in a GitHub repository.
 *
 * @param {{ owner: string, repo: string, branch: string, baseBranch: string, title: string, body: string, issueNumber: number }} params
 * @returns {Promise<{ prNumber: number, prUrl: string }>}
 */
export async function createDraftPr({ owner, repo, branch, baseBranch, title, body, issueNumber }) {
  const fullBody = `${body}\n\n---\n_Closes #${issueNumber}. Generated by Fiona coding agent._`;

  const { data } = await githubRequest(owner, repo, 'POST', `/repos/${owner}/${repo}/pulls`, {
    title,
    body: fullBody,
    head: branch,
    base: baseBranch,
    draft: true,
  });

  return {
    prNumber: data.number,
    prUrl: data.html_url,
  };
}
